const formatValue = (value: any): string => {
    if (value === null || value === undefined) {
        return "";
    }
    const stringValue = String(value);
    if (/[",\n]/.test(stringValue)) {
        return `"${stringValue.replace(/"/g, '""')}"`;
    }
    return stringValue;
};

const createCSV = (headers: string[], data: any[], metadata: any): string => {
    const now = new Date();

    let csvContent = "";
    csvContent += `# GradeX Report\n`;
    csvContent += `# Generated on: ${now.toLocaleString()}\n`;
    if (metadata.generatedBy) {
        csvContent += `# Generated by: ${metadata.generatedBy}\n`;
    }
    if (metadata.filters && Object.keys(metadata.filters).length > 0) {
        const filterString = Object.entries(metadata.filters).map(([k, v]) => `${k}: ${v}`).join(', ');
        csvContent += `# Filters Applied: ${filterString}\n`;
    }
    csvContent += "\n";

    // Create CSV content from an array of objects
    const headerRow = headers.map(formatValue).join(',');
    const dataRows = data.map(row =>
        headers.map(header => formatValue(row[header as keyof typeof row])).join(',')
    );

    return `${csvContent}${headerRow}\n${dataRows.join('\n')}`;
};

