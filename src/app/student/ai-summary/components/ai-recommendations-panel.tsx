"use client";

import {
  Card,
  CardContent,
  CardDescription,
  CardHeader,
  CardTitle,
} from "@/components/ui/card";
import { Skeleton } from "@/components/ui/skeleton";
import type { Student } from "@/lib/data";
import { type PersonalizedRecommendationsOutput } from "@/ai/flows/generate-personalized-recommendations";
import {
  BookOpen,
  TrendingUp,
  ShieldAlert,
  Lightbulb,
} from "lucide-react";

const RecommendationCategory = ({
  icon,
  title,
  text,
  isLoading,
}: {
  icon: React.ReactNode;
  title: string;
  text: string | undefined;
  isLoading: boolean;
}) => {
  if (isLoading) {
    return (
      <div className="flex gap-4">
        <Skeleton className="h-6 w-6 mt-1 rounded" />
        <div className="flex-1 space-y-2">
          <Skeleton className="h-5 w-32" />
          <Skeleton className="h-4 w-full" />
          <Skeleton className="h-4 w-4/5" />
          <Skeleton className="h-4 w-3/5" />
        </div>
      </div>
    );
  }

  if (!text) {
    return null;
  }

  return (
    <div className="flex gap-4">
      <div className="text-primary mt-1">{icon}</div>
      <div className="flex-1">
        <h3 className="font-semibold text-card-foreground mb-1">{title}</h3>
        <p className="text-sm text-muted-foreground">{text}</p>
      </div>
    </div>
  );
};

type RecommendationsData = Partial<Student> &
  Partial<PersonalizedRecommendationsOutput>;

export function AIRecommendationsPanel({
  recommendationsData,
  isLoading,
}: {
  recommendationsData: RecommendationsData;
  isLoading: boolean;
}) {
  const recommendations = {
    academic: recommendationsData.academicRecommendations,
    behavioral: recommendationsData.behavioralRecommendations,
    intervention: recommendationsData.interventionRecommendations,
  };

  const hasRecommendations =
    recommendations.academic ||
    recommendations.behavioral ||
    recommendations.intervention;

  return (
    <Card>
      <CardHeader>
        <CardTitle className="flex items-center gap-2">
          <Lightbulb className="w-6 h-6 text-primary" />
          AI-Powered Recommendations
        </CardTitle>
        <CardDescription>
          Personalized advice based on the latest AI analysis.
        </CardDescription>
      </CardHeader>
      <CardContent>
        {isLoading ? (
          <div className="space-y-6">
            <RecommendationCategory
              icon={<BookOpen className="w-5 h-5" />}
              title="Academic"
              text={undefined}
              isLoading={true}
            />
            <RecommendationCategory
              icon={<TrendingUp className="w-5 h-5" />}
              title="Behavioral"
              text={undefined}
              isLoading={true}
            />
            <RecommendationCategory
              icon={<ShieldAlert className="w-5 h-5" />}
              title="Intervention"
              text={undefined}
              isLoading={true}
            />
          </div>
        ) : !hasRecommendations ? (
          <div className="flex flex-col items-center justify-center text-center p-8 border-2 border-dashed rounded-lg bg-muted/20">
            <p className="text-muted-foreground">
              Recommendations are generated by your administrator.
            </p>
          </div>
        ) : (
          <div className="space-y-6">
            <RecommendationCategory
              icon={<BookOpen className="w-5 h-5" />}
              title="Academic"
              text={recommendations.academic}
              isLoading={false}
            />
            <RecommendationCategory
              icon={<TrendingUp className="w-5 h-5" />}
              title="Behavioral"
              text={recommendations.behavioral}
              isLoading={false}
            />
            <RecommendationCategory
              icon={<ShieldAlert className="w-5 h-5" />}
              title="Intervention"
              text={recommendations.intervention}
              isLoading={false}
            />
          </div>
        )}
      </CardContent>
    </Card>
  );
}
