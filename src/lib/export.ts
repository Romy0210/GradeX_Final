
'use client';

import { type Student } from '@/lib/data';

type ExportMetadata = {
    generatedBy: string | null | undefined;
    filters?: Record<string, string>;
};

type MonitoredData = {
    studentId: string;
    studentName: string;
    subjectName: string;
    batch: string;
    class: string;
    semester: string;
    attendancePercentage: number;
    totalAssignments: number;
    completedAssignments: number;
};

const formatValue = (value: any): string => {
    if (value === null || value === undefined) {
        return "";
    }
    const stringValue = String(value);
    // Escape quotes and wrap in quotes if it contains commas, quotes, or newlines
    if (/[",\n]/.test(stringValue)) {
        return `"${stringValue.replace(/"/g, '""')}"`;
    }
    return stringValue;
};

const createCSV = (headers: string[], data: any[], metadata: ExportMetadata): string => {
    const now = new Date();
    
    // Create metadata header
    let csvContent = "";
    csvContent += `# GradeX Report\n`;
    csvContent += `# Generated on: ${now.toLocaleString()}\n`;
    if (metadata.generatedBy) {
        csvContent += `# Generated by: ${metadata.generatedBy}\n`;
    }
    if (metadata.filters && Object.keys(metadata.filters).length > 0) {
        const filterString = Object.entries(metadata.filters).map(([k, v]) => `${k}: ${v}`).join(', ');
        csvContent += `# Filters Applied: ${filterString}\n`;
    }
    csvContent += "\n"; // Blank line before headers

    // Create CSV content from an array of objects
    const headerRow = headers.map(formatValue).join(',');
    const dataRows = data.map(row => 
        headers.map(header => formatValue(row[header as keyof typeof row])).join(',')
    );

    return `${csvContent}${headerRow}\n${dataRows.join('\n')}`;
};

const downloadCSV = (csvContent: string, fileName: string) => {
    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const link = document.createElement("a");
    const url = URL.createObjectURL(blob);
    link.setAttribute("href", url);
    link.setAttribute("download", fileName);
    link.style.visibility = 'hidden';
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
};

// Specific export functions

export const exportStandardReport = (students: Student[], metadata: ExportMetadata, fileName: string) => {
    const displayHeaders = [
        'Batch',
        'Class / Department',
        'Semester',
        'Roll Number',
        'Student Name',
        'GPA',
        'Overall Attendance (%)',
        'Subject',
        'Internal Mark 1',
        'Internal Mark 2',
        'Subject Attendance (%)',
        'Subject Risk',
        'Subject Outcome',
        'Subject Grade',
        'Confidence (%)',
    ];

    const data: Record<string, any>[] = [];
    students.forEach(student => {
        const hasSubjects = student.subjects && student.subjects.length > 0;

        if (hasSubjects) {
            student.subjects!.forEach(subject => {
                const subjectAnalysis = student.subjectAnalyses?.find(sa => sa.subjectId === subject.subjectId);
                
                data.push({
                    'Batch': student.batch,
                    'Class / Department': student.class,
                    'Semester': student.semester,
                    'Roll Number': student.id,
                    'Student Name': student.name,
                    'GPA': student.gpa.toFixed(1),
                    'Overall Attendance (%)': student.attendancePercentage.toFixed(1),
                    'Subject': subject.subjectName,
                    'Internal Mark 1': subject.internalMark1,
                    'Internal Mark 2': subject.internalMark2,
                    'Subject Attendance (%)': subject.subjectAttendancePercentage,
                    'Subject Risk': subjectAnalysis?.riskLevel ?? 'N/A',
                    'Subject Outcome': subjectAnalysis?.outcome ?? 'N/A',
                    'Subject Grade': subjectAnalysis?.gradeCategory ?? 'N/A',
                    'Confidence (%)': student.predictionConfidence?.toFixed(0) ?? student.failureRiskProbability?.toFixed(0) ?? 'N/A',
                });
            });
        } else {
             data.push({
                'Batch': student.batch,
                'Class / Department': student.class,
                'Semester': student.semester,
                'Roll Number': student.id,
                'Student Name': student.name,
                'GPA': student.gpa.toFixed(1),
                'Overall Attendance (%)': student.attendancePercentage.toFixed(1),
                'Subject': 'No Subjects Assigned',
                'Internal Mark 1': 'N/A',
                'Internal Mark 2': 'N/A',
                'Subject Attendance (%)': 'N/A',
                'Subject Risk': student.riskLevel,
                'Subject Outcome': student.outcome,
                'Subject Grade': student.gradeCategory,
                'Confidence (%)': student.predictionConfidence?.toFixed(0) ?? student.failureRiskProbability?.toFixed(0) ?? 'N/A',
            });
        }
    });

    const csvContent = createCSV(displayHeaders, data, metadata);
    downloadCSV(csvContent, fileName);
};


const getRiskReason = (student: Student): string => {
  const reasons = [];
  if (student.gpa < 6.5) reasons.push('Low GPA');
  if (student.attendancePercentage < 80) reasons.push('Low Attendance');
  if (student.assignmentCompletionPercentage < 70) reasons.push('Low Assignment Completion');
  if (student.pendingAssignments >= 3) reasons.push('High Pending Assignments');
  if(reasons.length === 0) return "N/A";
  return reasons.join('; ');
}


export const exportHighRiskReport = (students: Student[], metadata: ExportMetadata, fileName: string) => {
    const headers = [
        'id', 'name', 'batch', 'class', 'semester', 'gpa', 
        'attendancePercentage', 'pendingAssignments', 'riskReason'
    ];
    const displayHeaders = headers.map(h => h === 'id' ? 'rollNumber' : h);

    const highRiskStudents = students.filter(s => s.riskLevel === 'High');
    const data = highRiskStudents.map(s => ({
        id: s.id,
        name: s.name,
        batch: s.batch,
        class: s.class,
        semester: s.semester,
        gpa: s.gpa,
        attendancePercentage: s.attendancePercentage,
        pendingAssignments: s.pendingAssignments,
        riskReason: getRiskReason(s)
    }));

     const csvContent = createCSV(displayHeaders, data.map(row => {
        const newRow: Record<string, any> = {};
        Object.keys(row).forEach((key, i) => {
            newRow[displayHeaders[i]] = (row as any)[key];
        });
        return newRow;
    }), metadata);
    downloadCSV(csvContent, fileName);
};

export const exportAllStudentsReport = (students: Student[], metadata: ExportMetadata, fileName: string) => {
    const headers = [
        'id', 'name', 'email', 'age', 'gender', 'phone', 'educationalBackground',
        'batch', 'class', 'semester', 'gpa', 'internalMark1', 'internalMark2',
        'overallAverageMarkPercentage', 'attendancePercentage', 'assignmentCompletion',
        'pendingAssignments', 'assignmentCompletionPercentage', 'riskLevel', 'outcome',
        'gradeCategory', 'predictionConfidence', 'failureRiskProbability'
    ];
    // Rename 'id' to 'rollNumber' in the headers for display
    const displayHeaders = headers.map(h => h === 'id' ? 'rollNumber' : h);

    const data = students.map(row => {
        const rowData: { [key: string]: any } = {};
        headers.forEach(header => {
            if (header === 'internalMark1') {
                rowData['internalMark1'] = row.subjects?.map(sub => sub.internalMark1).join(';') ?? '';
            } else if (header === 'internalMark2') {
                rowData['internalMark2'] = row.subjects?.map(sub => sub.internalMark2).join(';') ?? '';
            } else {
                 const key = header as keyof Student;
                 // Special handling for the key rename
                const displayKey = key === 'id' ? 'rollNumber' : key;
                rowData[displayKey] = row[key] ?? "";
            }
        });
        return rowData;
    });

    const csvContent = createCSV(displayHeaders, data, metadata);
    downloadCSV(csvContent, fileName);
};

export const exportAttendanceReport = (data: MonitoredData[], metadata: ExportMetadata, fileName: string) => {
    const headers = [
        'Roll Number', 'Student Name', 'Batch', 'Class', 'Semester', 'Subject', 
        'Attendance %', 'Risk Level', 'Total Sessions', 'Present', 'Absent'
    ];
    
    const TOTAL_SESSIONS = 60;
    const getAttendanceRisk = (percentage: number): 'Low' | 'Medium' | 'High' => {
        if (percentage < 75) return 'High';
        if (percentage < 85) return 'Medium';
        return 'Low';
    };

    const reportData = data.map(item => {
        const present = Math.round(TOTAL_SESSIONS * (item.attendancePercentage / 100));
        const absent = TOTAL_SESSIONS - present;
        return {
            'Roll Number': item.studentId,
            'Student Name': item.studentName,
            'Batch': item.batch,
            'Class': item.class,
            'Semester': item.semester,
            'Subject': item.subjectName,
            'Attendance %': item.attendancePercentage.toFixed(1),
            'Risk Level': getAttendanceRisk(item.attendancePercentage),
            'Total Sessions': TOTAL_SESSIONS,
            'Present': present,
            'Absent': absent,
        };
    });

    const csvContent = createCSV(headers, reportData, metadata);
    downloadCSV(csvContent, fileName);
};


export const exportAssignmentsReport = (data: MonitoredData[], metadata: ExportMetadata, fileName: string) => {
    const headers = [
        'Roll Number', 'Student Name', 'Batch', 'Class', 'Semester', 'Subject',
        'Total Assignments', 'Completed', 'Pending', 'Completion %', 'Risk Level'
    ];

    const getAssignmentRisk = (completionPercentage: number): 'Low' | 'Medium' | 'High' => {
        if (completionPercentage < 40) return 'High';
        if (completionPercentage < 70) return 'Medium';
        return 'Low';
    };

    const reportData = data.map(item => {
        const pending = item.totalAssignments - item.completedAssignments;
        const completionPercentage = item.totalAssignments > 0 ? (item.completedAssignments / item.totalAssignments) * 100 : 100;
        return {
            'Roll Number': item.studentId,
            'Student Name': item.studentName,
            'Batch': item.batch,
            'Class': item.class,
            'Semester': item.semester,
            'Subject': item.subjectName,
            'Total Assignments': item.totalAssignments,
            'Completed': item.completedAssignments,
            'Pending': pending < 0 ? 0 : pending,
            'Completion %': completionPercentage.toFixed(1),
            'Risk Level': getAssignmentRisk(completionPercentage),
        };
    });

    const csvContent = createCSV(headers, reportData, metadata);
    downloadCSV(csvContent, fileName);
};
